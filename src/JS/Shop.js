  let age = document.getElementById("age-filter").value;
  let size = document.getElementById("size-filter").value;
  let gender = document.getElementById("gender-filter").value;

  // Main Sub Filters
  let jersey = document.getElementById("jersey-type")?.value || "all";
  let boot = document.querySelector("#boot-filter select")?.value || "all";
  let football = document.querySelector("#football-filter select")?.value || "all";
  let accessories = document.querySelector("#accessories-filter select")?.value || "all";


  let club = document.querySelector("#jersey-club")?.value || "all";
  let national = document.querySelector("#jersey-national-filter select")?.value || "all";
  
